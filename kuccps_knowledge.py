"""Small, local retrieval layer for verified KUCCPS reference material.

The corpus is generated by scripts/ingest_kuccps_knowledge.py and stored as
JSONL. This module deliberately uses only the Python standard library.
"""
from __future__ import annotations

import json
import math
import os
import re
import threading
from pathlib import Path
from urllib.parse import urlparse

OFFICIAL_HOSTS = {
    "kuccps.net",
    "www.kuccps.net",
    "statics.kuccps.net",
    "kuccps.ac.ke",
    "www.kuccps.ac.ke",
    "students.kuccps.ac.ke",
    "students.kuccps.net",  # legacy official student portal links
}
DEFAULT_CORPUS = Path(__file__).resolve().parent / "knowledge" / "kuccps_corpus.jsonl"
DEFAULT_CATALOG = Path(__file__).resolve().parent / "knowledge" / "course_catalog.jsonl"
_lock = threading.Lock()
_cached_signature = None
_cached_documents = []
_STOP_WORDS = set("a an and are as at be by can do for from how i in is it of on or the to was what when where which who why with you your kenya kuccps".split())


def _tokens(value: str) -> list[str]:
    return [word for word in re.findall(r"[a-z0-9+.-]{2,}", (value or "").lower()) if word not in _STOP_WORDS]


def _corpus_path() -> Path:
    configured = os.getenv("KUCCPS_KNOWLEDGE_PATH")
    return Path(configured).expanduser() if configured else DEFAULT_CORPUS


def _load_documents() -> list[dict]:
    global _cached_signature, _cached_documents
    paths = (_corpus_path(), Path(os.getenv("KUCCPS_CATALOG_PATH", str(DEFAULT_CATALOG))).expanduser())
    signatures = []
    for path in paths:
        try:
            stat = path.stat()
            signatures.append((str(path.resolve()), stat.st_mtime_ns, stat.st_size))
        except OSError:
            signatures.append((str(path), None, None))
    signature = tuple(signatures)
    if not any(item[1] is not None for item in signatures):
        return []
    with _lock:
        if signature == _cached_signature:
            return _cached_documents
        documents = []
        for path in paths:
            try:
                with path.open("r", encoding="utf-8") as corpus:
                    for line in corpus:
                        try:
                            item = json.loads(line)
                        except (json.JSONDecodeError, TypeError):
                            continue
                        content = re.sub(r"\s+", " ", str(item.get("content", ""))).strip()
                        if item.get("source_type") == "course_catalog":
                            item["source_label"] = f"Courses Checker course catalog snapshot — {item.get('database', '')}/{item.get('collection', '')}"
                        else:
                            url = item.get("url", "")
                            host = (urlparse(url).hostname or "").lower()
                            if host not in OFFICIAL_HOSTS:
                                continue
                            item["source_label"] = "Official KUCCPS reference"
                        if content:
                            item["content"] = content
                            item["_tokens"] = _tokens(f"{item.get('title', '')} {content}")
                            if item["_tokens"]:
                                documents.append(item)
            except OSError:
                continue
        _cached_signature, _cached_documents = signature, documents
        return documents


def retrieve(query: str, limit: int = 5) -> list[dict]:
    """Return the best local official source passages for a query."""
    query_tokens = _tokens(query)
    if not query_tokens:
        return []
    documents = _load_documents()
    if not documents:
        return []
    df = {}
    for document in documents:
        for token in set(document["_tokens"]):
            df[token] = df.get(token, 0) + 1
    average_length = sum(len(document["_tokens"]) for document in documents) / len(documents)
    ranked = []
    for document in documents:
        terms = document["_tokens"]
        frequencies = {}
        for token in terms:
            frequencies[token] = frequencies.get(token, 0) + 1
        score = 0.0
        for token in set(query_tokens):
            frequency = frequencies.get(token, 0)
            if frequency:
                inverse = math.log(1 + (len(documents) - df.get(token, 0) + 0.5) / (df.get(token, 0) + 0.5))
                score += inverse * (frequency * 2.2) / (frequency + 1.2 * (0.25 + 0.75 * len(terms) / max(average_length, 1)))
        title_tokens = set(_tokens(document.get("title", "")))
        score += 1.5 * len(set(query_tokens) & title_tokens)
        if score:
            ranked.append((score, document))
    ranked.sort(key=lambda item: item[0], reverse=True)
    results, seen = [], set()
    for score, document in ranked:
        identity = document.get("url") or "|".join((
            document.get("source_type", ""), document.get("database", ""),
            document.get("collection", ""), document.get("title", ""),
            document.get("content", ""),
        ))
        if identity in seen:
            continue
        seen.add(identity)
        results.append(dict(document, score=round(score, 3)))
        if len(results) >= max(1, limit):
            break
    return results


def format_context(documents: list[dict], max_chars: int = 8500) -> str:
    """Format retrieved material with explicit source labels for the model."""
    sections = []
    remaining = max_chars
    for document in documents:
        snippet = document["content"][:min(2400, remaining)]
        if not snippet:
            break
        sections.append(
            f"SOURCE: {document.get('source_label', 'Official KUCCPS reference')} — {document.get('title') or 'reference'}\n"
            f"URL: {document.get('url', 'Not applicable; local course catalog snapshot')}\n"
            f"Last fetched/indexed: {document.get('fetched_at') or document.get('indexed_at', 'unknown')}\n"
            f"CONTENT: {snippet}"
        )
        remaining -= len(snippet)
        if remaining <= 0:
            break
    return "\n\n---\n\n".join(sections)


def official_url(url: str) -> bool:
    """True only for HTTPS pages hosted on the configured official domains."""
    parsed = urlparse(url or "")
    host = (parsed.hostname or "").lower()
    return parsed.scheme == "https" and host in OFFICIAL_HOSTS
